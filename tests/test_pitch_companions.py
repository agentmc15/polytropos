"""Live-tree guard for the companions of the printable pitch, under docs/pitch/.

- docs/pitch/spec-driven-pitch.md is the Markdown form of docs/spec-driven-pitch.html (a
  hand-written page). It must carry every heading of the HTML deck, so the two cannot drift
  apart silently.
- docs/pitch/core-four.md maps Spec Kit's four core phases to polytropos; docs/pitch/sdd-report.md
  is the full field report on spec-driven development and how polytropos maps to it. Each .md is
  the source of a printable .html beside it, generated by docs/pitch/render.py and never
  hand-edited: the HTML must equal a fresh render, and must meet the deck's structure rules.

Every file goes through the deck's truth checks (tests/test_spec_driven_pitch.py): every bin
script, skill and repo path they name exists, there are no model ids, no rotting counts or
percentages, and no unlabeled dollar figures. The checks are imported from that module, not
copied. docs/pitch/ is a subdirectory on purpose: bin/docs_build.py mirrors only docs/*.md, so
these files add no generated page. The test reads the real tree and writes nothing.
"""
import html
import re
import unittest
from pathlib import Path

import importlib.util

import test_spec_driven_pitch as pitch

REPO_ROOT = Path(__file__).resolve().parent.parent
DECK_HTML = REPO_ROOT / "docs" / "spec-driven-pitch.html"
DECK_MD = REPO_ROOT / "docs" / "pitch" / "spec-driven-pitch.md"
MAP_MD = REPO_ROOT / "docs" / "pitch" / "core-four.md"
MAP_HTML = REPO_ROOT / "docs" / "pitch" / "core-four.html"
REPORT_MD = REPO_ROOT / "docs" / "pitch" / "sdd-report.md"
REPORT_HTML = REPO_ROOT / "docs" / "pitch" / "sdd-report.html"
RENDER = REPO_ROOT / "docs" / "pitch" / "render.py"

# The field report is longer than the deck: more printed pages, more words per document.
REPORT_PAGES = (5, 9)
REPORT_WORDS = (2400, 4500)
REPORT_SECTIONS = ("Summary", "What spec-driven development is", "The landscape",
                   "The principles, and how polytropos meets them", "Framework by framework",
                   "The criticisms of SDD, and how polytropos answers them",
                   "Gaps and recommendations", "Sources")
REPORT_FRAMEWORKS = ("Spec Kit", "Kiro", "OpenSpec", "BMAD", "Tessl")
PRINCIPLE_ROW = re.compile(r"^\| P(\d+) \|", re.MULTILINE)
PRINCIPLE_BULLET = re.compile(r"^- \*\*P(\d+) ·", re.MULTILINE)

CORE_FOUR = ("Specify", "Plan", "Tasks", "Implement")
HTML_HEADING = re.compile(r"<h([1-3])\b[^>]*>(.*?)</h\1>", re.DOTALL)
MD_HEADING = re.compile(r"^#{1,3} (.+)$", re.MULTILINE)
# The Markdown deck numbers its pages in the heading ("2 · The spec ..."); the HTML does not.
PAGE_NUMBER = re.compile(r"^\d+ · ")


def _norm(s):
    s = html.unescape(re.sub(r"<[^>]+>", "", s))
    s = s.replace("`", "").replace("**", "").replace("*", "")
    s = PAGE_NUMBER.sub("", s.strip())
    return " ".join(s.split()).casefold()


def html_headings(text):
    return [_norm(m.group(2)) for m in HTML_HEADING.finditer(text)]


def md_headings(text):
    return [_norm(m) for m in MD_HEADING.findall(text)]


def check_headings_carried(html_text, md_text, both_ways=False):
    """Every heading of the HTML must appear in the Markdown (and the reverse if both_ways)."""
    in_md = set(md_headings(md_text))
    missing = [h for h in html_headings(html_text) if h not in in_md]
    if missing:
        raise AssertionError(f"headings missing from the Markdown form: {missing}")
    if both_ways:
        in_html = set(html_headings(html_text))
        extra = [h for h in md_headings(md_text) if h not in in_html]
        if extra:
            raise AssertionError(f"headings missing from the HTML form: {extra}")


def _read(path):
    return path.read_text(encoding="utf-8")


def _load_render():
    spec = importlib.util.spec_from_file_location("pitch_render", RENDER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class FilesExistTests(unittest.TestCase):
    def test_files_exist(self):
        for path in (DECK_MD, MAP_MD, MAP_HTML, REPORT_MD, REPORT_HTML, RENDER):
            with self.subTest(path=path.name):
                self.assertTrue(path.is_file(), f"{path} is missing")


class DeckMarkdownTests(unittest.TestCase):
    def test_carries_every_deck_heading(self):
        check_headings_carried(_read(DECK_HTML), _read(DECK_MD))

    def test_carries_the_ledger_sample_and_run_commands(self):
        md = _read(DECK_MD)
        for line in ("outcome: T3 model=sonnet attempts=1 result=pass review=clean",
                     "defect: T5 kind=tautological-verify",
                     "python3 bin/routing_scorecard.py --history"):
            self.assertIn(line, md)

    def test_names_its_html_twin(self):
        self.assertIn("docs/spec-driven-pitch.html", _read(DECK_MD))

    def test_truth(self):
        pitch.check_truth(_read(DECK_MD), REPO_ROOT)


class CoreFourTests(unittest.TestCase):
    def test_html_structure_and_length(self):
        text = _read(MAP_HTML)
        pitch.check_structure(text, REPO_ROOT)
        pitch.check_lengths(text, REPO_ROOT)

    def test_html_and_markdown_carry_the_same_headings(self):
        check_headings_carried(_read(MAP_HTML), _read(MAP_MD), both_ways=True)

    def test_each_core_phase_has_its_own_section(self):
        heads = md_headings(_read(MAP_MD))
        for phase in CORE_FOUR:
            with self.subTest(phase=phase):
                self.assertTrue(any(h.endswith(phase.casefold()) for h in heads),
                                f"no section heading for {phase}")

    def test_truth(self):
        for path in (MAP_MD, MAP_HTML):
            with self.subTest(path=path.name):
                pitch.check_truth(_read(path), REPO_ROOT)


class RenderDriftTests(unittest.TestCase):
    def test_every_report_html_matches_a_fresh_render(self):
        for path, text in _load_render().rendered().items():
            with self.subTest(path=path.name):
                self.assertEqual(_read(path), text,
                                 f"{path.name} is stale: run python3 docs/pitch/render.py build")

    def test_renders_both_reports(self):
        names = {p.name for p in _load_render().rendered()}
        self.assertEqual(names, {"core-four.html", "sdd-report.html"})


class FieldReportTests(unittest.TestCase):
    def test_html_structure_and_length(self):
        text = _read(REPORT_HTML)
        pitch.check_structure(text, REPO_ROOT, *REPORT_PAGES)
        pitch.check_lengths(text, REPO_ROOT, *REPORT_WORDS)

    def test_html_and_markdown_carry_the_same_headings(self):
        check_headings_carried(_read(REPORT_HTML), _read(REPORT_MD), both_ways=True)

    def test_required_sections_present(self):
        heads = set(md_headings(_read(REPORT_MD)))
        for section in REPORT_SECTIONS:
            with self.subTest(section=section):
                self.assertIn(_norm(section), heads)

    def test_each_framework_has_its_own_section(self):
        heads = set(md_headings(_read(REPORT_MD)))
        for name in REPORT_FRAMEWORKS:
            with self.subTest(framework=name):
                self.assertIn(_norm(name), heads)

    def test_principles_are_numbered_without_gaps(self):
        md = _read(REPORT_MD)
        numbers = [int(n) for n in PRINCIPLE_ROW.findall(md) + PRINCIPLE_BULLET.findall(md)]
        self.assertTrue(numbers, "no principles found")
        self.assertEqual(numbers, list(range(1, len(numbers) + 1)))

    def test_points_at_its_companions(self):
        md = _read(REPORT_MD)
        for ref in ("docs/pitch/core-four.md", "docs/SPEC-DRIVEN.md", "docs/spec-driven-pitch.html"):
            self.assertIn(ref, md)

    def test_truth(self):
        for path in (REPORT_MD, REPORT_HTML):
            with self.subTest(path=path.name):
                pitch.check_truth(_read(path), REPO_ROOT)


class NegativeFixtureTests(unittest.TestCase):
    """The heading check must be able to fail; otherwise the live pass proves nothing."""

    def test_missing_heading_fails(self):
        with self.assertRaisesRegex(AssertionError, "missing from the Markdown"):
            check_headings_carried("<h2>The <em>ledger</em></h2><h3>Gone</h3>",
                                   "## The ledger\n")

    def test_extra_markdown_heading_fails_both_ways(self):
        with self.assertRaisesRegex(AssertionError, "missing from the HTML"):
            check_headings_carried("<h2>One</h2>", "## One\n## Two\n", both_ways=True)

    def test_render_reflects_a_markdown_edit(self):
        render = _load_render()
        before = render.render("# T\n\nIntro.\n\n## A\n\nBody.\n", "k")
        after = render.render("# T\n\nIntro.\n\n## B\n\nBody.\n", "k")
        self.assertNotEqual(before, after)
        self.assertIn("<h2>B</h2>", after)

    def test_render_page_marker_and_bold_code(self):
        out = _load_render().render("# T\n\nIntro.\n\n<!-- page -->\n\nA **`x`** y.\n", "k")
        self.assertEqual(out.count('<section class="page"'), 2)
        self.assertIn("<strong><code>x</code></strong>", out)

    def test_matching_headings_pass(self):
        check_headings_carried("<h2>The <code>ledger</code> &amp; more</h2>",
                               "## The `ledger` & more\n", both_ways=True)


if __name__ == "__main__":
    unittest.main()
